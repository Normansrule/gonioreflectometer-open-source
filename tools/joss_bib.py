#!/usr/bin/env python3
"""paper/joss/paper.bib: the entries of paper/references.bib that paper/joss/paper.md cites (keys = REFERENCES.md IDs).

    python tools/joss_bib.py       (run by `make paper`)
SPDX-License-Identifier: GPL-3.0-or-later
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JOSS = ROOT / "paper" / "joss"


def main() -> int:
    md = (JOSS / "paper.md").read_text(encoding="utf-8")
    keys = sorted(set(re.findall(r"@([A-Za-z]+\d+)", md.split("---", 2)[-1])))
    bib = (ROOT / "paper" / "references.bib").read_text(encoding="utf-8")
    entries = {m.group(1): m.group(0) for m in re.finditer(r"@\w+\{(\w+),.*?\n\}\n", bib, re.S)}
    missing = [k for k in keys if k not in entries]
    if missing:
        print("joss_bib: cited but not in REFERENCES.md:", ", ".join(missing))
        return 1
    out = "% generated by tools/joss_bib.py from paper/references.bib (REFERENCES.md); do not edit\n\n"
    out += "\n".join(entries[k] for k in keys)
    (JOSS / "paper.bib").write_text(out, encoding="utf-8")
    print(f"paper/joss/paper.bib: {len(keys)} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())

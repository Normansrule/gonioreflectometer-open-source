"""docs/render.html assets from the offline render pipeline (opengonio.render.demo): run by hand, `make render`.

Writes docs/render-data.js (materials: truth, fit, samples; scan numbers) and docs/assets/render/
(mug_hull.glb, shader_ball.glb and the software renderer's pictures). Simulated data only: the page says so.
Not part of `make build`: carving + smoothing are float-heavy, and other machines may differ in the last bit.
"""
from __future__ import annotations

import json
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "software" / "src"))

from opengonio.gantry.config import load_config  # noqa: E402
from opengonio.render.demo import THETA_I, THETA_R, run  # noqa: E402

OUT = ROOT / "docs" / "assets" / "render"
KEEP = ("mug_hull.glb", "shader_ball.glb")


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        rep = run(load_config().with_phase(12), tmp, size=300)
        OUT.mkdir(parents=True, exist_ok=True)
        pics = []
        for f in sorted(Path(tmp).iterdir()):
            if f.suffix == ".png" or f.name in KEEP:
                shutil.copyfile(f, OUT / f.name)
                if f.suffix == ".png":
                    pics.append(f.name)
    rep.pop("files", None)
    data = {"note": "Generated by tools/render_assets.py (make render) from opengonio.render.demo: simulated, not measured.",
            "plan": {"theta_i": list(THETA_I), "theta_r": list(THETA_R), "noise_pct": 2},
            "materials": rep["materials"], "scan": rep["scan"], "pictures": pics,
            "mesh": {"mug": "assets/render/mug_hull.glb", "ball": "assets/render/shader_ball.glb"}}
    (ROOT / "docs" / "render-data.js").write_text(
        "/* " + data["note"] + " */\nwindow.RENDER = " + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"render assets: {len(pics)} pictures, {rep['scan']['triangles']} hull triangles -> docs/assets/render/, docs/render-data.js")
    return 0


if __name__ == "__main__":
    sys.exit(main())
